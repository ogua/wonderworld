      <h2>Purpose</h2>
      <p>The purpose of the Anti-Bullying Policy at Wonder World International School is to
        promote a secure and happy environment where all can learn without fear of being bullied.
        Bullying is anti-social behaviour that affects everyone; it is unacceptable and will not
        be tolerated at our school.</p>

      <h2>Definition of Bullying</h2>
      <p>Bullying is intentional, repeated behaviour by an individual or group that causes
        physical or emotional harm to another person or group. It can manifest in various forms,
        including physical, verbal, relational, and cyberbullying.</p>

      <h2>Objectives</h2>
      <ul>
        <li>To ensure that all students, staff, and parents understand what bullying is.</li>
        <li>To ensure a consistent school response to any bullying incidents that may occur.</li>
        <li>To establish a school climate where bullying is regarded as unacceptable, so that a
          safe and secure environment is created for everyone.</li>
      </ul>

      <h2>Preventive Measures</h2>
      <ul>
        <li>Regular awareness and education programs for students, staff, and parents.</li>
        <li>Integration of social skills programs in our curriculum focusing on respect, empathy,
          and assertiveness.</li>
        <li>Monitoring of key areas within the school where bullying is likely to occur.</li>
        <li>Encouragement of students to report any bullying incident they witness or
          experience to school personnel.</li>
      </ul>

      <h2>Procedures for Reporting Bullying</h2>
      <ul>
        <li>Students are encouraged to speak to any staff member if they are being bullied or if
          they see others being bullied. Staff members will refer these reports to the designated
          Anti-Bullying Coordinator.</li>
        <li>Parents can report bullying incidents directly to the school by contacting the
          student's teacher or the Anti-Bullying Coordinator via email or phone.</li>
        <li>All reports of bullying will be documented and investigated promptly and
          thoroughly.</li>
      </ul>

      <h2>Response to Bullying</h2>
      <ul>
        <li>All reported incidents of bullying will be taken seriously and handled with
          sensitivity.</li>
        <li>Support will be offered to all parties involved, including the victim(s), the
          bystander(s), and the perpetrator(s).</li>
        <li>Actions taken will include mediation and counseling, along with appropriate
          disciplinary measures.</li>
        <li>Serious cases may result in suspension or expulsion in accordance with school
          policy.</li>
      </ul>

      <h2>Follow-Up</h2>
      <ul>
        <li>Follow-up meetings with the involved parties will be conducted to ensure the bullying
          has stopped and that no further issues have occurred.</li>
        <li>Regular feedback sessions with the affected parties to monitor the situation and
          ensure the effectiveness of the response.</li>
      </ul>

      <h2>Communication</h2>
      <ul>
        <li>This policy is available to all staff, students, and parents. It is included in the
          school's welcome package for new students and displayed on the school's website.</li>
        <li>The policy is reviewed annually by the school board to ensure its effectiveness and
          to make any necessary adjustments.</li>
      </ul>

      <h2>Support Structures</h2>
      <ul>
        <li>The school provides counseling services available to all students affected by
          bullying.</li>
        <li>Training is provided for all staff to recognize bullying behaviours and to intervene
          effectively.</li>
      </ul>

      <p>By implementing this Anti-Bullying Policy, Wonder World International School commits to
        leading the way in preventing, addressing, and eliminating bullying, ensuring that our
        school remains a safe and welcoming place for everyone.</p>
