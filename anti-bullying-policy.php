                <div class="text-center mx-auto mb-5 wow fadeInUp" data-wow-delay="0.1s" style="max-width: 600px;">
                    <h1 class="mb-3">Anti-Bullying Policy</h1>
                    <p>APPLICATION PROCEDURE /ADMISSION STEPS</p>
                </div>
                <div class="wow fadeInUp" data-wow-delay="0.1s">

                    <p class="wow fadeInUp" data-wow-delay="0.2s"><b> Purpose: </b> <br>
The purpose of the Anti-Bullying Policy at Wonder World International School is to promote a secure and happy environment where all can learn without fear of being bullied. Bullying is anti-social behavior that affects everyone; it is unacceptable and will not be tolerated at our school.</p>

                    <p class="wow fadeInUp" data-wow-delay="0.2s"><b> Definition of Bullying: </b> <br>
Bullying is intentional, repeated behavior by an individual or group that causes physical or emotional harm to another person or group. It can manifest in various forms, including physical, verbal, relational, and cyberbullying.</p>

                    <p class="wow fadeInUp" data-wow-delay="0.2s"><b> Objectives: </b> <br>

    •  To ensure that all students, staff, and parents understand what bullying is. <br>
    •  To ensure a consistent school response to any bullying incidents that may occur. <br>
    •  To establish a school climate where bullying is regarded as unacceptable so that a safe and secure environment is created for everyone.</p>

    <p class="wow fadeInUp" data-wow-delay="0.2s"><b> Preventive Measures: </b> <br>
    • Regular awareness and education programs for students, staff, and parents. <br>
    • Integration of social skills programs in our curriculum focusing on respect, empathy, and assertiveness. <br>
    • Monitoring of key areas within the school where bullying is likely to occur. <br>
    • Encouragement of students to report any bullying incident they witness or experience to school personnel.</p>

                    <p class="wow fadeInUp" data-wow-delay="0.2s"><b> Procedures for Reporting Bullying:</b> <br>
    • Students are encouraged to speak to any staff member if they are being bullied or if they see others being bullied. Staff members will refer these reports to the designated Anti-Bullying Coordinator. <br>
    • Parents can report bullying incidents directly to the school by contacting the student’s teacher or the Anti-Bullying Coordinator via email or phone. <br>
    • All reports of bullying will be documented and investigated promptly and thoroughly.</p>

                    <p class="wow fadeInUp" data-wow-delay="0.2s"><b> Response to Bullying:</b> <br>
    • All reported incidents of bullying will be taken seriously and handled with sensitivity. <br>
    • Support will be offered to all parties involved, including the victim(s), the bystander(s), and the perpetrator(s). <br>
    • Actions taken will include mediation and counseling, along with appropriate disciplinary measures. <br>
    • Serious cases may result in suspension or expulsion in accordance with school policy.</p>

                    <p class="wow fadeInUp" data-wow-delay="0.2s"><b> Follow-Up:</b> <br>
    • Follow-up meetings with the involved parties will be conducted to ensure the bullying has stopped and that no further issues have occurred. <br>
    • Regular feedback sessions with the affected parties to monitor the situation and ensure the effectiveness of the response.</p>

                    <p class="mt-3 wow fadeInUp" data-wow-delay="0.3s"><b> Communication:</b>  <br>
    • This policy will be available to all staff, students, and parents. It will be included in the school’s welcome package for new students and displayed on the school’s website. <br>
    • The policy will be reviewed annually by the school board to ensure its effectiveness and to make any necessary adjustments.</p>

                    <p class="mt-3 wow fadeInUp" data-wow-delay="0.3s"><b> Support Structures: </b> <br>
    • The school provides counseling services available to all students affected by bullying. <br>
    • Training will be provided for all staff to recognize bullying behaviors and to intervene effectively.</p>

                    <p class="mt-3 wow fadeInUp" data-wow-delay="0.3s">By implementing this Anti-Bullying Policy, Wonder World International School commits to leading the way in preventing, addressing, and eliminating bullying, ensuring that our school remains a safe and welcoming place for everyone.</p>


